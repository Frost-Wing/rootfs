# Real partition installer
# ============================================================================

def get_block_device_info(
    device: str,
) -> str:
    """
    Return human-readable information about a block device.
    """
    result = sudo(
        [
            "lsblk",
            "-o",
            "NAME,SIZE,TYPE,FSTYPE,LABEL,MOUNTPOINTS,MODEL",
            device,
        ],
        capture_output=True,
        check=False,
    )

    return result.stdout.strip()


def device_exists(
    device: Path,
) -> bool:
    """
    Check whether the specified path exists and is a block device.
    """
    if not device.is_absolute():
        return False

    try:
        return (
            os.path.exists(device)
            and os.path.exists(
                f"/sys/class/block/{device.name}"
            )
        )
    except OSError:
        return False


def get_block_device_type(
    device: str,
) -> str | None:
    """
    Return the lsblk TYPE for the exact supplied device.

    Expected result for installation is:

        part
    """
    result = subprocess.run(
        [
            "lsblk",
            "-dn",
            "-o",
            "TYPE",
            device,
        ],
        capture_output=True,
        text=True,
        check=False,
    )

    device_type = result.stdout.strip()

    if not device_type:
        return None

    return device_type


def is_partition(
    device: str,
) -> bool:
    """
    Return True only when the exact target device is an lsblk partition.

    lsblk reports partitions as TYPE=part.
    """
    return get_block_device_type(device) == "part"


def is_whole_disk(
    device: str,
) -> bool:
    """
    Return True when the exact target is an lsblk whole disk.
    """
    return get_block_device_type(device) == "disk"


def get_mountpoints(
    device: str,
) -> list[str]:
    """
    Return mountpoints associated with a device.
    """
    result = sudo(
        [
            "lsblk",
            "-n",
            "-o",
            "MOUNTPOINTS",
            device,
        ],
        capture_output=True,
        check=False,
    )

    return [
        line.strip()
        for line in result.stdout.splitlines()
        if line.strip()
    ]


def install_rootfs(
    device: str,
) -> None:
    """
    Install Frost onto a REAL PARTITION.

    THIS IS DESTRUCTIVE.

    The target must be an actual lsblk partition (TYPE=part).
    Whole disks (TYPE=disk), loop devices, etc. are rejected.

    The target partition is formatted as ext2 and frost-root.ready/
    is copied onto it.
    """
    section(
        "FROST INSTALLER"
    )

    require_commands(
        [
            "sudo",
            "lsblk",
            "mkfs.ext2",
            "mount",
            "umount",
            "cp",
        ]
    )

    # ----------------------------------------------------------------
    # Verify generated Frost filesystem.
    # ----------------------------------------------------------------

    if not FROST_READY_ROOT.exists():
        error(
            f"{FROST_READY_ROOT} does not exist."
        )

        error(
            "Run 'build-rootfs' first."
        )

        sys.exit(1)

    target = Path(device)

    # ----------------------------------------------------------------
    # Absolute path required.
    # ----------------------------------------------------------------

    if not target.is_absolute():
        error(
            "Target must be an absolute device path."
        )

        error(
            "Example: /dev/sda2"
        )

        error(
            "Example: /dev/nvme0n1p3"
        )

        sys.exit(1)

    # ----------------------------------------------------------------
    # Device must exist and be a block device.
    # ----------------------------------------------------------------

    if not device_exists(target):
        error(
            f"{target} does not appear to be a valid block device."
        )

        sys.exit(1)

    # ----------------------------------------------------------------
    # Identify exact target TYPE before anything destructive.
    # ----------------------------------------------------------------

    device_type = get_block_device_type(
        str(target)
    )

    if device_type is None:
        error(
            f"Could not determine the device type of {target}."
        )

        error(
            "Refusing to continue."
        )

        sys.exit(1)

    print()

    print(
        f"{BOLD}Target device type:{RESET} "
        f"{device_type}"
    )

    # ----------------------------------------------------------------
    # HARD partition-only safety check.
    #
    # Only TYPE=part is accepted.
    # ----------------------------------------------------------------

    if not is_partition(str(target)):
        print()

        if is_whole_disk(str(target)):
            error(
                "REFUSING TO INSTALL ON A WHOLE DISK."
            )
        else:
            error(
                f"REFUSING TO INSTALL ON {target}: "
                f"device type is '{device_type}', "
                "not 'part'."
            )

        error(
            "The install command accepts PARTITIONS ONLY."
        )

        error(
            "Examples of accepted targets:"
        )

        error(
            "    /dev/sda2"
        )

        error(
            "    /dev/nvme0n1p3"
        )

        error(
            "    /dev/mmcblk0p1"
        )

        error(
            "The complete disk must never be supplied."
        )

        sys.exit(1)

    # ----------------------------------------------------------------
    # MASSIVE WARNING.
    # ----------------------------------------------------------------

    print()

    print(
        f"{RED}{BOLD}"
        "!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!"
        f"{RESET}"
    )

    print(
        f"{RED}{BOLD}"
        "!!             DESTRUCTIVE OPERATION         !!"
        f"{RESET}"
    )

    print(
        f"{RED}{BOLD}"
        "!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!"
        f"{RESET}"
    )

    print()

    warn(
        "THE SELECTED PARTITION WILL BE FORMATTED."
    )

    warn(
        "ALL DATA CURRENTLY STORED ON IT WILL BE ERASED."
    )

    warn(
        "THIS OPERATION CANNOT BE UNDONE."
    )

    print()

    print(
        f"{BOLD}Target:{RESET} {target}"
    )

    print()

    # ----------------------------------------------------------------
    # Show device information.
    # ----------------------------------------------------------------

    print(
        get_block_device_info(
            str(target)
        )
    )

    print()

    # ----------------------------------------------------------------
    # Refuse mounted targets.
    # ----------------------------------------------------------------

    mountpoints = get_mountpoints(
        str(target)
    )

    if mountpoints:
        error(
            "TARGET PARTITION IS CURRENTLY MOUNTED:"
        )

        for mountpoint in mountpoints:
            error(
                f"    {mountpoint}"
            )

        print()

        error(
            "Unmount the partition before continuing."
        )

        sys.exit(1)

    # ----------------------------------------------------------------
    # First confirmation.
    # ----------------------------------------------------------------

    print()

    print(
        f"{BOLD}"
        "To continue, type the EXACT device path:"
        f"{RESET}"
    )

    typed_device = input(
        ">>> "
    ).strip()

    if typed_device != str(target):
        error(
            "Device path did not match."
        )

        error(
            "Installation cancelled."
        )

        sys.exit(1)

    # ----------------------------------------------------------------
    # Second confirmation.
    # ----------------------------------------------------------------

    print()

    print(
        f"{RED}{BOLD}"
        "FINAL WARNING"
        f"{RESET}"
    )

    print()

    print(
        f"This will ERASE {target}."
    )

    print(
        "The partition will be formatted as ext2."
    )

    print(
        "Frost OS will then be copied onto it."
    )

    print()

    confirmation = input(
        f"{RED}{BOLD}"
        f"Type 'ERASE {target.name}' to continue: "
        f"{RESET}"
    ).strip()

    if confirmation != f"ERASE {target.name}":
        error(
            "Final confirmation failed."
        )

        error(
            "Installation cancelled."
        )

        sys.exit(1)

    # ----------------------------------------------------------------
    # Re-check exact target immediately before formatting.
    # ----------------------------------------------------------------

    final_type = get_block_device_type(
        str(target)
    )

    if final_type != "part":
        error(
            "Target changed state: "
            f"expected partition, got {final_type!r}."
        )

        error(
            "Refusing to format it."
        )

        sys.exit(1)

    # ----------------------------------------------------------------
    # Format.
    # ----------------------------------------------------------------

    section(
        "Formatting target"
    )

    info(
        f"Formatting partition {target} as ext2..."
    )

    sudo(
        [
            "mkfs.ext2",
            "-F",
            str(target),
        ]
    )

    # ----------------------------------------------------------------
    # Temporary mount directory.
    # ----------------------------------------------------------------

    mount_dir = Path(
        tempfile.mkdtemp(
            prefix="frost-install-",
            dir="/tmp",
        )
    )

    mounted = False

    try:
        # ------------------------------------------------------------
        # Mount.
        # ------------------------------------------------------------

        info(
            f"Mounting {target}..."
        )

        sudo(
            [
                "mount",
                str(target),
                str(mount_dir),
            ]
        )

        mounted = True

        # ------------------------------------------------------------
        # Copy generated final Frost filesystem.
        # ------------------------------------------------------------

        section(
            "Installing Frost filesystem"
        )

        info(
            "Copying frost-root.ready..."
        )

        sudo(
            [
                "cp",
                "-a",
                f"{FROST_READY_ROOT}/.",
                f"{mount_dir}/",
            ]
        )

        # ------------------------------------------------------------
        # Synchronize.
        # ------------------------------------------------------------

        info(
            "Synchronizing filesystem..."
        )

        sudo(
            [
                "sync"
            ]
        )

        ok(
            "Frost filesystem copied successfully."
        )

    finally:
        # ------------------------------------------------------------
        # Unmount.
        # ------------------------------------------------------------

        if mounted:
            info(
                "Unmounting target..."
            )

            sudo(
                [
                    "umount",
                    str(mount_dir),
                ],
                check=False,
            )

        # ------------------------------------------------------------
        # Remove temporary mount directory.
        # ------------------------------------------------------------

        try:
            mount_dir.rmdir()
        except OSError:
            pass

    # ----------------------------------------------------------------
    # Finished.
    # ----------------------------------------------------------------

    section(
        "Installation complete"
    )

    ok(
        f"Frost OS installed to partition {target}"
    )

    warn(
        "The partition contains an ext2 filesystem."
    )

    warn(
        "No bootloader was installed."
    )


# ============================================================================
# Argument parser
# ============================================================================

def build_parser() -> argparse.ArgumentParser:
    """
    Construct the command-line interface.
    """
    parser = argparse.ArgumentParser(
        description=(
            "Frost OS root filesystem and disk image builder."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:

    Build root filesystem:
        %(prog)s build-rootfs

    Build disk image from frost-root.ready:
        %(prog)s build-image

    Build everything:
        %(prog)s build

    Clean generated artifacts:
        %(prog)s clean

    Install onto a PARTITION:
        %(prog)s install /dev/sda2
        %(prog)s install /dev/nvme0n1p3

The install command rejects whole disks and accepts only lsblk TYPE=part.
""",
    )

    subparsers = parser.add_subparsers(
        dest="command",
        required=True,
    )

    # ----------------------------------------------------------------
    # build-rootfs
    # ----------------------------------------------------------------

    subparsers.add_parser(
        "build-rootfs",
        help=(
            "Create arch-root, clone frost-root to frost-root.ready, "
            "and merge Arch into the ready tree"
        ),
    )

    # ----------------------------------------------------------------
    # build-image
    # ----------------------------------------------------------------

    subparsers.add_parser(
        "build-image",
        help=(
            "Create disk.img from frost-root.ready"
        ),
    )

    # ----------------------------------------------------------------
    # build
    # ----------------------------------------------------------------

    subparsers.add_parser(
        "build",
        help=(
            "Build frost-root.ready and disk.img"
        ),
    )

    # ----------------------------------------------------------------
    # clean
    # ----------------------------------------------------------------

    subparsers.add_parser(
        "clean",
        help=(
            "Remove disk.img, frost-root.ready, and arch-root "
            "(never frost-root)"
        ),
    )

    # ----------------------------------------------------------------
    # install
    # ----------------------------------------------------------------

    install_parser = subparsers.add_parser(
        "install",
        help=(
            "DESTRUCTIVELY install Frost onto a PARTITION"
        ),
    )

    install_parser.add_argument(
        "device",
        help=(
            "Target partition, e.g. /dev/sda2"
        ),
    )

    return parser


# ============================================================================
# Main
# ============================================================================

def main() -> int:
    """
    Program entry point.
    """
    parser = build_parser()
    args = parser.parse_args()

    try:
        # ------------------------------------------------------------
        # Build root filesystem.
        # ------------------------------------------------------------

        if args.command == "build-rootfs":
            build_rootfs()

        # ------------------------------------------------------------
        # Build disk image.
        # ------------------------------------------------------------

        elif args.command == "build-image":
            create_disk_image()

        # ------------------------------------------------------------
        # Build everything.
        # ------------------------------------------------------------

        elif args.command == "build":
            build_rootfs()
            create_disk_image()

        # ------------------------------------------------------------
        # Clean.
        # ------------------------------------------------------------

        elif args.command == "clean":
            clean()

        # ------------------------------------------------------------
        # Install onto real partition.
        # ------------------------------------------------------------

        elif args.command == "install":
            install_rootfs(
                args.device
            )

        else:
            parser.print_help()
            return 1

    except KeyboardInterrupt:
        print()

        warn(
            "Operation interrupted by user."
        )

        return 130

    except subprocess.CalledProcessError as exc:
        print()

        error(
            f"Command failed with exit status "
            f"{exc.returncode}."
        )

        return exc.returncode

    except Exception as exc:
        print()

        error(
            str(exc)
        )

        return 1

    return 0


if __name__ == "__main__":
    raise SystemExit(
        main()
    )